"""Generate SOURCE_COVERAGE.md: response-by-response matrix from audit.json + chapters + logs."""
import csv, json, re, sys
from collections import Counter
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from registry import CHAPTERS, github_slug, strip_emoji

ROOT = Path(__file__).resolve().parent.parent
audit = json.loads((ROOT / "_work" / "audit.json").read_text(encoding="utf-8"))
meta = json.loads((ROOT / "_work" / "build-meta.json").read_text(encoding="utf-8"))
titles = meta["titles"]

trims = {}
for row in csv.reader(l for l in (ROOT / "_work" / "trims.csv").read_text(encoding="utf-8").splitlines() if not l.startswith("#")):
    if row[0].isdigit():
        trims[int(row[0])] = (int(row[1]), int(row[2]))

# corrections tags per chapter
tags = {n: Counter() for n in CHAPTERS}
cur = None
for ln in (ROOT / "docs/00-start-here/corrections-log-by-chapter.md").read_text(encoding="utf-8").splitlines():
    m = re.match(r"^## Ch(\d+)", ln)
    if m:
        cur = int(m.group(1)); continue
    m = re.match(r"^- \[([A-Z/ -]+?)\]", ln)
    if m and cur:
        tags[cur][m.group(1).split("/")[0].split("-")[0] if False else m.group(1)] += 1

def headings(path):
    txt = path.read_text(encoding="utf-8")
    body = txt.split("<!-- SOURCE-BEGIN -->")[1].split("<!-- SOURCE-END -->")[0]
    out, fence = [], False
    for ln in body.splitlines():
        if ln.startswith("```"):
            fence = not fence
        if not fence and ln.startswith("## "):
            out.append(ln[3:].strip())
    return out

rows, details = [], []
tot = Counter()
for n, ch in CHAPTERS.items():
    f = audit["fidelity"][str(n)]
    src = (ROOT / ch["src"]).read_text(encoding="utf-8").splitlines()
    ks, ke = trims[n]
    hs = headings(ROOT / ch["path"])
    sup = (ROOT / "supplements" / f"ch{n:02d}.md").exists()
    rev = (ROOT / "revision" / f"ch{n:02d}-revision.md").exists()
    t = tags[n]
    flagged = sum(c for k, c in t.items() if k.startswith(("VERIFY", "VERSION")))
    corr = sum(c for k, c in t.items() if k.startswith(("CORRECTION", "SECURITY", "BACKREF", "PRACTICAL", "INCOMPLETE", "SELF", "SUPERSEDED", "INCONSISTENCY", "PLACEHOLDER", "DUAL", "LIBRARY")))
    status = "lossless" if f["ok"] else "**MISMATCH**"
    rows.append(
        f"| {n} | {titles[str(n)]} | {len(src)} | {ks}–{ke} | {f['removed_nonempty']} | {f['kept_nonempty']} = {f['out_nonempty']} | "
        f"{len(hs)} | {f['code_blocks']} = {f['code_blocks_out']} | {f['tables']} = {f['tables_out']} | "
        f"{'yes' if sup else '–'} | {'yes' if rev else '–'} | {corr} / {flagged} | {status} |")
    tot.update(src=len(src), kept=f["kept_nonempty"], removed=f["removed_nonempty"], code=f["code_blocks"], secs=len(hs), tables=f["tables"])
    d = [f"<details><summary><b>Chapter {n}</b> — {titles[str(n)]} ({len(hs)} sections)</summary>", "",
         f"Source: `{ch['src']}` lines {ks}–{ke} of {len(src)} → [{ch['file']}](docs/{ch['domain']}/{ch['file']}). Removed lines: "
         f"[removed-scaffolding.md](docs/00-start-here/removed-scaffolding.md#chapter-{n}).", ""]
    for h in hs:
        d.append(f"- [{strip_emoji(h)}](docs/{ch['domain']}/{ch['file']}#{github_slug(h)})")
    d += ["", "</details>", ""]
    details += d


out = f"""# Source Coverage Matrix

Response-by-response accounting of the source conversation → this knowledge base. Generated by `tools/gen_coverage.py` from the independent audit ([AUDIT_REPORT.md](AUDIT_REPORT.md), `_work/audit.json`).

## Headline

- Source files with content: **36** (files 1–36). The task description said 37; files 37–40 supplied are **empty** (0 bytes). File 36 is a stand-alone *Virtualization Internals — Deep Dive* (imported as Chapter 36); the "Response 36 — Final DevOps Mastery" that Chapter 35 promises **does not exist** in the supplied material. Nothing was invented to fill the gap. See [PROGRESS.md](PROGRESS.md).
- Source lines: **{tot['src']:,}** (including removed scaffolding). Non-empty lines kept verbatim in chapters: **{tot['kept']:,}**; removed non-empty lines: **{tot['removed']:,}**, every one of which appears verbatim in [removed-scaffolding.md](docs/00-start-here/removed-scaffolding.md).
- Source fenced code blocks: **{tot['code']:,}**, all present in output (counts equal per chapter). Tables: **{tot['tables']}** source, all present.
- Result of the independent source→output comparison: **{f'all {len(CHAPTERS)} chapters lossless' if audit['all_chapters_lossless'] else 'MISMATCHES — see audit'}**.

## How to read the matrix

| Column | Meaning |
|---|---|
| Src lines | total lines in `source-archive/src-NN.txt` |
| Kept lines | the line range imported into the chapter (the rest is removed scaffolding: progress tables, next-teasers, meta replies) |
| Removed | non-empty lines removed; preserved verbatim in `removed-scaffolding.md` |
| Kept = Out | non-empty source lines kept = non-empty lines found in the chapter's SOURCE region (must be equal) |
| § | `##` sections in the chapter (source top-level headings) |
| Code | fenced blocks in source = in output |
| Tables | Markdown tables in source = in output |
| Supp. / Rev. | editorial supplement / revision sheet exists |
| Corr / Verify | entries in the corrections log of types correction-like / version-or-verify |

Note on counting: the audit canonicalises both sides (strips the documented mechanical transformations) before comparing, so "equal" means *identical content*, not just equal counts.

## Matrix

| Resp. | Title | Src lines | Kept lines | Removed | Kept = Out | § | Code | Tables | Supp. | Rev. | Corr / Verify | Status |
|---:|---|---:|---|---:|---|---:|---|---|---|---|---|---|
""" + "\n".join(rows) + f"""

Empty source files (supplied, 0 bytes, not archived): `Response1 copy 37.txt` … `Response1 copy 40.txt`. The audit found no material outside files 1–36.

## What was removed (and why it is safe)

Only three kinds of text were removed from chapters, all pure scaffolding of the original chat: (1) "📍 Roadmap Progress" tables and `n/24`, `n/36` counters, (2) "Next → Response N" teasers, (3) conversational replies addressed to the user (before Chapters 2, 8, 11, 15, 18, 36). The scope clarifications inside (3) are *content* about the course design, so they are kept readable in [course-design-notes.md](docs/00-start-here/course-design-notes.md); the rest is in [removed-scaffolding.md](docs/00-start-here/removed-scaffolding.md). The roadmap table itself is kept in [roadmap.md](docs/00-start-here/roadmap.md).

## Output → source (nothing invented)

Every line inside `<!-- SOURCE-BEGIN -->…<!-- SOURCE-END -->` maps to the source. Everything outside those markers is editorial and labelled: the chapter header, navigation footer, the "Editorial supplement" sections ({sum(1 for n in CHAPTERS if (ROOT/'supplements'/f'ch{n:02d}.md').exists())} chapters), revision sheets, glossary, comparisons/formulas/Q&A/playbooks, labs, the capstone starter, the website, and this audit material.

## Section-by-section index

Open a chapter to see its sections and jump straight to them.

""" + "\n".join(details) + "\n---\n[← Contents](CONTENTS.md)\n"
(ROOT / "SOURCE_COVERAGE.md").write_text(out, encoding="utf-8")
print("SOURCE_COVERAGE.md written", tot)
