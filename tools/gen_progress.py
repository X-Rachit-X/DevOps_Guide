"""Generate PROGRESS.md from the machine-readable audit/test results so the numbers cannot drift from reality.

Run after tools/audit.py (and optionally tools/test_website.py --crawl):  python -X utf8 tools/gen_progress.py
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from registry import CHAPTERS  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
W = ROOT / "_work"
audit = json.loads((W / "audit.json").read_text(encoding="utf-8"))
fid = audit["fidelity"]
n_ch = len(CHAPTERS)
src_lines = sum(len((ROOT / c["src"]).read_text(encoding="utf-8").splitlines()) for c in CHAPTERS.values())
kept = sum(v["kept_nonempty"] for v in fid.values())
removed = sum(v["removed_nonempty"] for v in fid.values())
code_blocks = sum(v["code_blocks"] for v in fid.values())
lossless = sum(1 for v in fid.values() if v["ok"])
supp = sorted(int(re.search(r"ch(\d+)", p.name).group(1)) for p in (ROOT / "supplements").glob("ch*.md"))
revs = len(list((ROOT / "revision").glob("ch*-revision.md")))
extracted = len(list((ROOT / "code-examples" / "extracted").rglob("*.*"))) - 0
extracted = sum(1 for p in (ROOT / "code-examples" / "extracted").rglob("*") if p.is_file())
glossary = len(re.findall(r"^- \*\*", (ROOT / "GLOSSARY.md").read_text(encoding="utf-8"), flags=re.M))
idx = json.loads((ROOT / "website/data/search-index.json").read_text(encoding="utf-8"))
code = audit["code"]
broken = audit["broken_links"]
test_file = W / "website-test.json"
tests = json.loads(test_file.read_text(encoding="utf-8")) if test_file.exists() else []
crawl_file = W / "website-crawl.json"
crawl = json.loads(crawl_file.read_text(encoding="utf-8")) if crawl_file.exists() else None
t_pass = sum(1 for t in tests if t["ok"])
t_fail = [t["test"] for t in tests if not t["ok"]]

def yn(b):
    return "yes" if b else "**NO**"

L = [
    "# Progress and Status",
    "",
    "Generated by `tools/gen_progress.py` from `_work/audit.json` and `_work/website-test.json`, so the numbers are measured, not hand-typed. "
    "Everything below is a statement about *this repository*; items marked **not done** or **not verified** are real gaps.",
    "",
    "## 1. Source inventory",
    "",
    "| Fact | Value |",
    "|---|---|",
    "| Source files supplied | 40 (`Response1 copy 1.txt` … `Response1 copy 40.txt`) |",
    "| Files with content | **36** (files 1–36) |",
    "| Empty files | **4** (files 37–40, 0 bytes) |",
    "| Number stated in the request | 37 — does **not** match the files (36 with content, 4 empty) |",
    "| Promised-but-absent response | Chapter 35 announces *Response 36 — Final Cloud + DevOps Mastery*; **it does not exist**. File 36 is a different, stand-alone *Virtualization Internals — Deep Dive* |",
    "| Late discovery | An earlier pass of this project treated file 36 as empty. It was caught during the final audit, and imported as Chapter 36 with glossary, corrections, supplement and revision sheet |",
    f"| Source lines (all files) | {src_lines:,} |",
    "",
    "## 2. Coverage and fidelity (measured by `tools/audit.py`)",
    "",
    f"- Chapters generated: **{n_ch}**; chapters whose output equals their source exactly (after normalising the documented mechanical transformations): **{lossless} / {n_ch}**.",
    f"- Non-empty source lines kept → found in chapters: **{kept:,}** (identical sequences). Removed non-empty lines: **{removed:,}**, each preserved verbatim in `docs/00-start-here/removed-scaffolding.md`.",
    f"- Fenced code blocks, headings and tables: counts equal in every chapter ({code_blocks:,} code blocks).",
    "- **Limit of this audit:** it proves the chapters equal the *kept range* of the source. Whether the removed ranges are genuinely scaffolding was checked by reading the first line of every removed block (they are progress tables, \"next response\" teasers and replies to meta-questions), not by an automatic classifier.",
    "",
    "## 3. Deliverables",
    "",
    "| Deliverable | State |",
    "|---|---|",
    f"| 36 chapters (`docs/`) | done — {lossless}/{n_ch} lossless |",
    f"| Revision sheets | {revs} per-chapter sheets + 6 cross-cutting sheets + index |",
    f"| Editorial supplements | chapters {', '.join(map(str, supp))} |",
    f"| Glossary | {glossary} entries (`GLOSSARY.md`) |",
    "| Corrections | `CORRECTIONS.md` (curated) + `docs/00-start-here/corrections-log-by-chapter.md` (full log) |",
    "| Source coverage matrix | `SOURCE_COVERAGE.md` (generated) |",
    "| Interview Q&A / comparisons / formulas / playbooks / traps | `revision/01…05` |",
    "| Labs | `exercises/labs.md` |",
    f"| Extracted code | {extracted} files under `code-examples/extracted/` + `INDEX.md` |",
    "| Capstone reference starter | `code-examples/capstone/` (editorial) |",
    f"| Website | `website/` — {len(idx):,} searchable sections |",
    "| Diagrams | The source's ASCII diagrams are preserved verbatim in the chapters (they render as code blocks); no new image diagrams were created |",
    "| Audit report | `AUDIT_REPORT.md` (generated) |",
    "",
    "## 4. Verification actually performed",
    "",
    "| Check | Result |",
    "|---|---|",
    f"| Source → output fidelity, 36 chapters | {lossless}/{n_ch} identical |",
    f"| Relative Markdown links | {audit['links_checked']:,} checked, **{len(broken)} broken** |",
    f"| Leftover `Response N` references in chapter text | {len(audit['text']['leftover_response_refs'])} |",
    f"| Code syntax (YAML, JSON, Bash only) | {code['passed']} passed, {len(code['failed'])} failed, {code['skipped']} skipped (templates/placeholders) |",
]
if tests:
    L += [f"| Website, headless Edge via Selenium | {t_pass}/{len(tests)} checks passed" + (f"; failed: {', '.join(t_fail)}" if t_fail else "") + " |"]
else:
    L += ["| Website, headless Edge | **not run** |"]
if crawl:
    L += [f"| Website crawl (all pages, all internal links and anchors as rendered) | {crawl['pages']} pages, {len(crawl['errors'])} load errors, {len(crawl['bad'])} unresolved links/anchors |"]
L += [
    "| Capstone starter | `npm ci`, `tsc --noEmit`, `tsc` build passed; YAML parses; `npm audit --omit=dev` found 0 vulnerabilities |",
    "| Web verification of version-sensitive facts | Argo CD `selfHeal`/`prune` defaults, Terraform S3 `use_lockfile` and DynamoDB-locking deprecation, public IPv4 charge, S3 default encryption, S3 Block Public Access default — see `CORRECTIONS.md` §D |",
    "",
    "## 5. Not done / not verified (read before relying on this)",
    "",
    "- **Terraform, Dockerfile, TypeScript, Helm, Jenkinsfile, Jinja snippets were not executed or linted** (no toolchain used); only YAML/JSON/Bash were machine-checked. Many source snippets are deliberately simplified.",
    "- **The capstone starter was not run end to end** (the Docker daemon was unavailable). The Kubernetes/KEDA manifests were not applied to a cluster and the CI workflow was not run on GitHub.",
    "- **Version-sensitive facts** flagged *verify* in `CORRECTIONS.md` (Terraform feature versions, Docker/Postgres image changes, App Mesh support dates, API Gateway quotas, EKS pricing, action/tool major versions) were **not** independently confirmed.",
    "- **Corrections marked *Reference*** cite the right official page but were not re-fetched here.",
    "- The commands in the Chapter 36 supplement are standard Linux tools but were not run (authoring machine is Windows).",
    "- **Not published:** nothing was committed, pushed, or deployed, and no repository or Pages setting was changed. Commands are in `README.md`. **No licence** was chosen.",
    "- The website was tested in one browser engine (Edge/Chromium, desktop and a 390 px viewport); Firefox and Safari were not tested.",
    "- Search is a plain substring match over section text, not a ranked full-text engine.",
    "- Completion tracking lives in `localStorage` for that browser only.",
    "",
    "## 6. Suggested next steps",
    "",
    "1. Skim `CORRECTIONS.md` §A–§D and decide which *verify* items matter for your target stack; re-check them against current official docs.",
    "2. Run the capstone starter (`docker compose up`) and fix whatever the first run reveals; implement the outbox gap it lists.",
    "3. Add a `LICENSE`, create the repository and enable GitHub Pages (commands in `README.md`).",
    "4. If the missing *Final DevOps Mastery* response exists elsewhere, drop it into `source-archive/src-37.txt` and add a registry/trims entry; the build and audit will pick it up.",
    "",
    "---",
    "[← Contents](CONTENTS.md)",
    "",
]
(ROOT / "PROGRESS.md").write_text("\n".join(L), encoding="utf-8", newline="\n")
print("PROGRESS.md written")
